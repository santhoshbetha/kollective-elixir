defmodule KollectiveWeb.PostJSON do
  alias Kollective.Media.PostMedia
  alias Kollective.Accounts.User

  def index(%{posts: posts, current_user: current_user}) do
    %{data: for(post <- posts, do: data(post, current_user))}
  end

  def index2(%{posts: posts}) do
    %{data: Enum.map(posts, &data2/1)}
  end

  def show2(%{post: post}) do
    %{data: data2(post)}
  end

  def data2(%{post: post, likes_count: count, has_liked: liked}) do
    is_deleted = !is_nil(post.deleted_at) #For Soft delete behavior (show "deleted" messsage in UI)
    %{
      id: post.id,
      body: if(is_deleted, do: "[post deleted]", else: post.body),
      author: if(is_deleted, do: nil, else: author_data(post.author)),
      likes_count: count, # <--- Include the virtual field
      has_liked: liked,
      parent_id: post.parent_id,
      in_reply_to_id: post.in_reply_to_id,
      # Recursively serialize replies if they exist
      replies: Enum.map(post.replies, &data2/1)
    }
  end

  defp author_data(%User{} = user) do
    %{
      id: user.id,
      username: user.username,
      avatar_url: user.avatar
    }
  end
  defp author_data(_), do: nil

  def show(%{post: post, current_user: current_user}) do
    %{data: data(post, current_user)}
  end

  def data(post, current_user) do
    %{
      id: post.id,
      content: post.content,
      status: post.status,
      inserted_at: post.inserted_at,

      # 1. Author/Candidate Details
      author: %{
        id: post.user.id,
        username: post.user.username,
        is_verified: post.user.is_verified,
        # Using the helper to get the avatar URL
        avatar_url: PostMedia.url({post.user.avatar, post.user}, :thumb)
      },

      # 2. Multi-Media Attachments (Up to 4)
      attachments: Enum.map(post.attachments || [], fn att ->
        is_video = String.starts_with?(att.content_type || "", "video")
        %{
          id: att.id,
          # signed: true for private R2 links
          url: PostMedia.url({att.media, att}, :original, signed: true),
          is_video: is_video,
          # Poster image generated by the FFmpeg worker for videos
          poster_url: if(is_video, do: PostMedia.url({att.media, att}, :poster, signed: true)),
          alt_text: att.alt_text
        }
      end),

      # 3. Engagement Stats & Counter Caches
      stats: %{
        comments_count: post.comments_count,
        reposts_count: post.reposts_count,
        # Check if the logged-in user has already interacted
        has_reposted: user_reposted?(post, current_user)
      }
    }
  end

  # Helper to check if the current user is in the preloaded reposts list
  defp user_reposted?(post, %{id: user_id}) do
    Enum.any?(post.reposts || [], &(&1.user_id == user_id))
  end
  defp user_reposted?(_, _), do: false

