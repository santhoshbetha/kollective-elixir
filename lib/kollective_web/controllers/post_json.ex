  # Entry point for the controller: render(:thread, tree: thread_tree)
  def thread(%{tree: tree}) do
    %{data: Enum.map(tree, &wrapped_post/1)}
  end

  # Serializes the map wrapper: %{post: post, likes_count: c, has_liked: l, replies: [...]}
  def wrapped_post(%{post: post, likes_count: likes_count, has_liked: has_liked, replies: replies}) do
    %{
      id: post.id,
      content: post.content,
      inserted_at: post.inserted_at,
      in_reply_to_id: post.in_reply_to_id,
      root_post_id: post.root_post_id,
      likes_count: likes_count,
      has_liked: has_liked,
      author: author_data(post.author),
      # RECURSION: Format the child replies by calling this function on them
      replies: Enum.map(replies, &wrapped_post/1)
    }
  end

